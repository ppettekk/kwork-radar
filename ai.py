"""Генерация черновика отклика через CloseRouter (OpenAI-совместимый API)."""

from __future__ import annotations

import logging
import re
from typing import Any

from openai import AsyncOpenAI

logger = logging.getLogger(__name__)

SYSTEM_PROMPT = """Ты пишешь отклики на заказы биржи Kwork от лица исполнителя.

СТРУКТУРА ОТКЛИКА

1. Первое слово: «Здравствуйте!» Дальше сразу по делу, без «меня зовут».
2. Одна фраза, показывающая, что ТЗ прочитано: своими словами, что нужно
   сделать. Не пересказывай задание целиком, заказчик его и так знает.
3. Ядро отклика: КАК ты это сделаешь. Конкретные шаги, инструменты, на что
   обратишь внимание, что заказчик получит на выходе и в каком виде.
   Именно план работы убеждает, а не рассказ о себе.
4. Один уточняющий вопрос в конце, если в ТЗ есть неясность. Вопрос должен
   быть по сути задачи, а не «расскажите подробнее».

ЧТО ГЛАВНОЕ

Отклик строится от задачи заказчика, а не от профиля исполнителя.
Профиль дан фоном: он показывает уровень, манеру речи и общий род занятий,
но это НЕ список разрешённых тем и НЕ ограничение.
Не пиши «это не мой профиль», «я специализируюсь на другом», «могу
порекомендовать коллегу». Любую задачу разбирай по существу и предлагай
конкретный план, даже если в профиле про эту область нет ни слова.
Решение, отправлять отклик или нет, принимает человек, а не ты.

ЛИЧНЫЕ ДАННЫЕ

Имя, возраст, город и статус занятости из фона используй только тогда,
когда это по делу: заказчик прямо спросил, задача привязана к городу,
важен часовой пояс для созвонов, нужен чек как от самозанятого.
В обычном отклике про себя ничего этого писать не надо, там говорит план
работы. Возраст не упоминай никогда, если о нём не спросили.

ОБЛАСТЬ ЗАДАЧИ

Сначала определи, о чём заказ, и говори на языке этой области.
Монтаж видео: раскадровка, склейка, цветокоррекция, чистка звука, титры,
переходы, форматы экспорта под площадку.
Дизайн: композиция, сетка, шрифтовые пары, цветовая схема, исходники,
вылеты под печать.
Тексты: структура, тон, целевая аудитория, вычитка.
Таблицы и данные: сведение источников, формулы, сводные, проверка на ошибки.
Разработка: стек, архитектура, интеграции.

Это критично: НЕ сводить любую задачу к коду. Если в ТЗ нет ни слова про
программирование, слова «код», «скрипт», «стек», «Python», «API», «интеграция»
в отклике запрещены полностью.

ЗАПРЕЩЕНО

- Выдумывать проверяемые факты: годы опыта, портфолио, количество заказов,
  прошлых клиентов, образование, сертификаты, названия компаний, отзывы.
  Всё это видно в профиле на Kwork рядом с откликом и сразу вскроется.
  Различай: «сделаю так-то и так-то» можно писать про любую задачу,
  «я делал это сто раз» нельзя.
  Вместо «я много лет монтирую» пиши «соберу по сценарию, вычищу звук,
  отдам в двух форматах». Второе убеждает сильнее и ничем не рискует.
- Сроки и любые упоминания времени: дни, недели, дедлайны, «быстро»,
  «оперативно», «в ближайшее время».
- Деньги: цена, бюджет, стоимость, оплата, предоплата, скидка.
- Тире любого вида. Перестраивай предложение: запятая, двоеточие, точка,
  связка «это».
- Эмодзи, markdown, списки, заголовки.
- Восклицательные знаки везде, кроме приветствия.
- Штампы: «имею богатый опыт», «качественно и в срок», «готов приступить
  немедленно», «буду рад сотрудничеству», «ответственный подход»,
  «в кратчайшие сроки», «работаю на результат».

ТОН

Живой человек, а не бот. Короткие предложения, простые слова, обращение
на «вы». Допустима лёгкая разговорность: «посмотрел ваше ТЗ», «сделаю так».
Никакого канцелярита и деловых оборотов.

ОБЪЁМ

5-8 предложений сплошным текстом, один абзац.

Отвечай SKIP одной строкой только если задачу физически невозможно выполнить
удалённо (нужно личное присутствие) или она требует лицензии либо допуска.
Незнакомая область поводом для SKIP не является: опиши, как подойдёшь к ней.

Верни только текст отклика. Без кавычек, пояснений и markdown."""

REPAIR_PROMPT = (
    "Перепиши этот текст так, чтобы в нём не осталось ни одного тире и дефиса "
    "между словами. Смысл, объём и тон сохрани. Верни только исправленный текст."
)

# Все виды тире и дефисов, которые встречаются в выводе моделей.
_DASHES = "\u2010\u2011\u2012\u2013\u2014\u2015\u2212\u2043\uFE58\uFE63\uFF0D"
_DASH_TABLE = {ord(ch): "-" for ch in _DASHES}

_SPACED_DASH = re.compile(r"\s+-\s+")
_LEADING_DASH = re.compile(r"^\s*-\s+", re.MULTILINE)


def dashes_to_hyphen(text: str) -> str:
    """Только замена тире, без чистки markdown: годится для чужого текста."""
    return text.translate(_DASH_TABLE)


def normalize(text: str) -> str:
    """Приводит текст к виду без длинных тире и markdown-разметки."""
    text = text.translate(_DASH_TABLE)
    text = re.sub(r"\*\*|__|`|#+\s*", "", text)
    text = _LEADING_DASH.sub("", text)          # маркеры списков
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def has_dash(text: str) -> bool:
    """Остался ли дефис в роли тире (между словами, с пробелами)."""
    return bool(_SPACED_DASH.search(text))


class DraftWriter:
    def __init__(
        self,
        api_key: str,
        base_url: str,
        model: str,
        profile: str = "",
        enabled: bool = True,
        repair_dashes: bool = True,
    ) -> None:
        self.enabled = enabled
        self.model = model
        self.profile = profile
        self.repair_dashes = repair_dashes
        self._client = (
            AsyncOpenAI(api_key=api_key, base_url=base_url, timeout=45.0)
            if enabled
            else None
        )

    def _user_prompt(self, project: dict[str, Any]) -> str:
        # Задача идёт первой: она определяет содержание отклика.
        parts = [
            "ЗАДАЧА ЗАКАЗЧИКА (главное, от этого пляши):\n"
            f"Заголовок: {project.get('title') or 'нет'}\n"
            f"Описание:\n{(project.get('description') or 'нет').strip()}"
        ]
        if self.profile:
            parts.append(
                "ФОН ОБ ИСПОЛНИТЕЛЕ (для тона и уровня, НЕ список разрешённых тем):\n"
                f"{self.profile}"
            )
        parts.append(
            "Напиши отклик именно на эту задачу. Если она из области, которой нет "
            "в фоне, всё равно разбери её по существу и предложи план."
        )
        return "\n\n".join(parts)

    async def _complete(self, messages: list[dict[str, str]], temperature: float) -> str:
        response = await self._client.chat.completions.create(
            model=self.model,
            max_tokens=600,
            temperature=temperature,
            messages=messages,
        )
        return (response.choices[0].message.content or "").strip()

    async def draft(self, project: dict[str, Any], temperature: float = 0.7) -> str | None:
        if not self.enabled or self._client is None:
            return None

        try:
            raw = await self._complete(
                [
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": self._user_prompt(project)},
                ],
                temperature,
            )
        except Exception:
            logger.exception("CloseRouter: не удалось сгенерировать отклик")
            return None

        if not raw:
            logger.warning("CloseRouter вернул пустой ответ")
            return None
        if raw.upper().startswith("SKIP"):
            logger.info(
                "SKIP: задача вне профиля, черновик не нужен (%s)",
                (project.get("title") or "")[:60],
            )
            return None

        text = normalize(raw)

        # Модель всё же поставила тире: один дешёвый проход на переписывание.
        if self.repair_dashes and has_dash(text):
            try:
                repaired = await self._complete(
                    [
                        {"role": "system", "content": REPAIR_PROMPT},
                        {"role": "user", "content": text},
                    ],
                    0.3,
                )
                if repaired:
                    candidate = normalize(repaired)
                    if not has_dash(candidate):
                        text = candidate
            except Exception:
                logger.warning("CloseRouter: проход по тире не удался, отдаю как есть")

        return text or None
